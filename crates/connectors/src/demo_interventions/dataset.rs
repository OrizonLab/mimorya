#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum InterventionStatus {
    Planned,
    InProgress,
    Completed,
    Cancelled,
}

#[derive(Debug, Clone, PartialEq)]
pub struct Intervention {
    pub id: &'static str,
    pub technician_id: Uuid,
    pub team_unit_id: Uuid,
    pub date: NaiveDate,
    /// HH:MM
    pub start_time: &'static str,
    pub duration_hours: f64,
    pub kind: &'static str,
    pub client: &'static str,
    pub city: &'static str,
    pub status: InterventionStatus,
    pub report: &'static str,
    pub parts_pending: Option<&'static str>,
    pub client_signature: bool,
    pub sensitivity: Sensitivity,
}

#[derive(Debug, Clone, PartialEq)]
pub struct Absence {
    pub technician_id: Uuid,
    pub date: NaiveDate,
    pub start_time: &'static str,
    pub end_time: &'static str,
    pub reason: &'static str,
}

/// Day `offset` from `monday` (negative: previous week).
fn day(monday: NaiveDate, offset: i64) -> NaiveDate {
    if offset >= 0 {
        monday.checked_add_days(Days::new(offset as u64))
    } else {
        monday.checked_sub_days(Days::new(offset.unsigned_abs()))
    }
    .expect("date in range")
}

